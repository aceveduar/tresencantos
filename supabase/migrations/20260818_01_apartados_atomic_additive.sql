CREATE OR REPLACE FUNCTION public.te_rpc_replay(
  p_request_id uuid,
  p_operation text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_row public.pos_rpc_requests%ROWTYPE;
BEGIN
  IF p_request_id IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'request_id es obligatorio';
  END IF;
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'No autenticado';
  END IF;

  -- Serializa dos reintentos simultaneos del mismo request_id.
  PERFORM pg_advisory_xact_lock(hashtextextended(p_request_id::text, 0));

  SELECT * INTO v_row
  FROM public.pos_rpc_requests
  WHERE request_id = p_request_id;

  IF NOT FOUND THEN
    RETURN NULL;
  END IF;
  IF v_row.actor_id <> auth.uid() OR v_row.operation <> p_operation THEN
    RAISE EXCEPTION USING
      ERRCODE = '22023',
      MESSAGE = 'request_id ya fue usado para otra operacion o usuario';
  END IF;
  RETURN v_row.response;
END;
$$;

CREATE OR REPLACE FUNCTION public.te_rpc_store(
  p_request_id uuid,
  p_operation text,
  p_sale_id bigint,
  p_response jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  INSERT INTO public.pos_rpc_requests (
    request_id, operation, actor_id, actor_email, sale_id, response
  ) VALUES (
    p_request_id,
    p_operation,
    auth.uid(),
    lower(auth.jwt() ->> 'email'),
    p_sale_id,
    p_response
  );
END;
$$;

-- Permite resolver un resultado ambiguo despues de recargar (por ejemplo, si
-- la red se corto justo despues del COMMIT). Nunca revela requests de otro
-- usuario y toma el mismo lock que las RPC de escritura.
CREATE OR REPLACE FUNCTION public.get_pos_rpc_result(p_request_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_response jsonb;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'No autenticado';
  END IF;
  IF p_request_id IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'request_id es obligatorio';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(p_request_id::text, 0));

  SELECT r.response INTO v_response
  FROM public.pos_rpc_requests r
  WHERE r.request_id = p_request_id
    AND r.actor_id = auth.uid();

  IF NOT FOUND THEN
    RETURN jsonb_build_object('found', false);
  END IF;
  RETURN jsonb_build_object('found', true, 'response', v_response);
END;
$$;

-- Normaliza items y toma el snapshot del kit DESDE products. Nunca confia en
-- kit_items enviados por el navegador.
CREATE OR REPLACE FUNCTION public.te_snapshot_sale_items(p_items jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_item              jsonb;
  v_component         jsonb;
  v_product           public.products%ROWTYPE;
  v_raw_id            numeric;
  v_raw_qty           numeric;
  v_raw_price         numeric;
  v_raw_component_id  numeric;
  v_raw_component_qty numeric;
  v_id                bigint;
  v_qty               integer;
  v_component_id      bigint;
  v_component_qty     integer;
  v_price             numeric;
  v_name              text;
  v_kit_snapshot      jsonb;
  v_snapshot          jsonb := '[]'::jsonb;
  v_normalized        jsonb;
BEGIN
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'La venta debe tener al menos un producto';
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_raw_id := public.te_try_numeric(v_item ->> 'id');
    v_raw_qty := public.te_try_numeric(v_item ->> 'qty');
    v_raw_price := public.te_try_numeric(v_item ->> 'price');

    IF v_raw_id IS NULL OR v_raw_id <= 0 OR v_raw_id <> trunc(v_raw_id)
       OR v_raw_id > 9223372036854775807::numeric THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Producto sin id valido';
    END IF;
    v_id := v_raw_id::bigint;

    IF v_raw_qty IS NULL OR v_raw_qty <= 0 OR v_raw_qty <> trunc(v_raw_qty)
       OR v_raw_qty > 2147483647::numeric THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = format('Cantidad invalida para producto id=%s', v_id);
    END IF;
    v_qty := v_raw_qty::integer;

    v_price := round(v_raw_price, 2);
    IF NOT public.te_numeric_is_finite(v_price) OR v_price < 0 THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = format('Precio invalido para producto id=%s', v_id);
    END IF;

    SELECT * INTO v_product
    FROM public.products
    WHERE id = v_id;
    IF NOT FOUND THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = format('Producto id=%s no existe', v_id);
    END IF;

    v_name := COALESCE(NULLIF(btrim(v_item ->> 'name'), ''), v_product.name);
    v_normalized := jsonb_build_object(
      'id', v_id,
      'name', v_name,
      'price', v_price,
      'qty', v_qty,
      'subtotal', round(v_price * v_qty, 2)
    );

    -- Valida y normaliza el kit que vive en base. Asi el snapshot nunca puede
    -- redondear un id/cantidad fraccional hacia otro producto por un cast.
    v_kit_snapshot := '[]'::jsonb;
    IF jsonb_typeof(v_product.kit_items) = 'array' THEN
      FOR v_component IN SELECT value FROM jsonb_array_elements(v_product.kit_items)
      LOOP
        v_raw_component_id := public.te_try_numeric(v_component ->> 'id');
        v_raw_component_qty := COALESCE(public.te_try_numeric(v_component ->> 'qty'), 1);

        IF v_raw_component_id IS NULL OR v_raw_component_id <= 0
           OR v_raw_component_id <> trunc(v_raw_component_id)
           OR v_raw_component_id > 9223372036854775807::numeric THEN
          RAISE EXCEPTION USING
            ERRCODE = '22023',
            MESSAGE = format('Kit id=%s contiene un componente sin id valido', v_id);
        END IF;
        IF v_raw_component_qty <= 0 OR v_raw_component_qty <> trunc(v_raw_component_qty)
           OR v_raw_component_qty > 2147483647::numeric THEN
          RAISE EXCEPTION USING
            ERRCODE = '22023',
            MESSAGE = format('Kit id=%s contiene una cantidad invalida', v_id);
        END IF;

        v_component_id := v_raw_component_id::bigint;
        v_component_qty := v_raw_component_qty::integer;
        v_kit_snapshot := v_kit_snapshot || jsonb_build_array(jsonb_build_object(
          'id', v_component_id,
          'name', NULLIF(btrim(v_component ->> 'name'), ''),
          'qty', v_component_qty
        ));
      END LOOP;
    END IF;

    -- Tambien se guarda [] para un producto regular. La presencia de la llave
    -- hace el snapshot autoritativo si ese producto se convierte en kit luego.
    v_normalized := v_normalized || jsonb_build_object(
      'kit_items', v_kit_snapshot,
      'kit_snapshot_estimated', false
    );

    v_snapshot := v_snapshot || jsonb_build_array(v_normalized);
  END LOOP;

  RETURN v_snapshot;
END;
$$;

-- Fusiona un snapshot nuevo (siempre construido en servidor) con los kits ya
-- congelados de la venta. Los productos nuevos conservan el kit actual; los
-- existentes nunca cambian de componentes por una edicion no relacionada.
CREATE OR REPLACE FUNCTION public.te_preserve_item_kit_snapshots(
  p_new_items jsonb,
  p_old_items jsonb
)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT COALESCE(jsonb_agg(
    CASE
      WHEN old_item.item IS NOT NULL
           AND jsonb_typeof(old_item.item -> 'kit_items') = 'array'
        THEN n.item || jsonb_build_object(
          'kit_items', old_item.item -> 'kit_items',
          'kit_snapshot_estimated', COALESCE(
            old_item.item -> 'kit_snapshot_estimated', 'true'::jsonb
          )
        )
      ELSE n.item
    END
    ORDER BY n.ord
  ), '[]'::jsonb)
  FROM jsonb_array_elements(
    CASE WHEN jsonb_typeof(p_new_items) = 'array' THEN p_new_items ELSE '[]'::jsonb END
  ) WITH ORDINALITY AS n(item, ord)
  LEFT JOIN LATERAL (
    SELECT o.item
    FROM jsonb_array_elements(
      CASE WHEN jsonb_typeof(p_old_items) = 'array' THEN p_old_items ELSE '[]'::jsonb END
    ) AS o(item)
    WHERE public.te_try_numeric(o.item ->> 'id') = public.te_try_numeric(n.item ->> 'id')
    LIMIT 1
  ) old_item ON true;
$$;

-- Expande items de venta a demanda real de inventario. Usa primero el snapshot
-- guardado; para filas historicas sin snapshot usa el kit actual como fallback.
CREATE OR REPLACE FUNCTION public.te_inventory_demand(p_items jsonb)
RETURNS TABLE(product_id bigint, required_qty bigint)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  WITH item_rows AS (
    SELECT
      item,
      public.te_require_positive_bigint(item ->> 'id', 'id de producto') AS item_id,
      public.te_require_positive_bigint(COALESCE(item ->> 'qty', '1'), 'cantidad de producto') AS item_qty
    FROM jsonb_array_elements(
      CASE WHEN jsonb_typeof(p_items) = 'array' THEN p_items ELSE '[]'::jsonb END
    ) AS x(item)
  ), item_sources AS (
    SELECT
      i.*,
      CASE
        -- Cualquier array presente, incluso [], es un snapshot autoritativo.
        WHEN jsonb_typeof(i.item -> 'kit_items') = 'array'
          THEN i.item -> 'kit_items'
        WHEN jsonb_typeof(p.kit_items) = 'array'
             AND jsonb_array_length(p.kit_items) > 0
          THEN p.kit_items
        ELSE '[]'::jsonb
      END AS kit_items
    FROM item_rows i
    LEFT JOIN public.products p ON p.id = i.item_id
  ), expanded AS (
    SELECT
      public.te_require_positive_bigint(component ->> 'id', 'id de componente') AS product_id,
      s.item_qty * public.te_require_positive_bigint(
        COALESCE(component ->> 'qty', '1'), 'cantidad de componente'
      ) AS required_qty
    FROM item_sources s
    CROSS JOIN LATERAL jsonb_array_elements(s.kit_items) AS k(component)
    WHERE jsonb_array_length(s.kit_items) > 0

    UNION ALL

    SELECT s.item_id, s.item_qty
    FROM item_sources s
    WHERE jsonb_array_length(s.kit_items) = 0
  )
  SELECT e.product_id, SUM(e.required_qty)::bigint
  FROM expanded e
  GROUP BY e.product_id
  ORDER BY e.product_id;
$$;

CREATE OR REPLACE FUNCTION public.te_assert_authoritative_inventory_snapshot(
  p_items jsonb,
  p_operation text
)
RETURNS void
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM jsonb_array_elements(
      CASE WHEN jsonb_typeof(p_items) = 'array' THEN p_items ELSE '[]'::jsonb END
    ) AS i(item)
    WHERE COALESCE((i.item ->> 'kit_snapshot_estimated')::boolean, false)
      AND jsonb_typeof(i.item -> 'kit_items') = 'array'
      AND jsonb_array_length(i.item -> 'kit_items') > 0
  ) THEN
