CREATE OR REPLACE FUNCTION public.te_require_positive_bigint(
  p_value text,
  p_label text DEFAULT 'valor'
)
RETURNS bigint
LANGUAGE plpgsql
IMMUTABLE
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_value numeric := public.te_try_numeric(p_value);
BEGIN
  IF v_value IS NULL OR v_value <= 0 OR v_value <> trunc(v_value)
     OR v_value > 9223372036854775807::numeric THEN
    RAISE EXCEPTION USING
      ERRCODE = '22023',
      MESSAGE = format('%s debe ser un entero positivo valido', COALESCE(p_label, 'valor'));
  END IF;
  RETURN v_value::bigint;
END;
$$;

CREATE OR REPLACE FUNCTION public.te_numeric_is_finite(p_value numeric)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
SET search_path = pg_catalog
AS $$
  SELECT p_value IS NOT NULL
     AND p_value::text NOT IN ('NaN', 'Infinity', '-Infinity');
$$;

-- Migra roles confiables a app_metadata. Nunca copia raw_user_meta_data: ese
-- campo puede modificarlo el propio usuario. config.user_permissions sigue
-- siendo la fuente administrable y tiene prioridad cuando contiene un rol
-- valido.
WITH permission_config AS (
  SELECT COALESCE(public.te_try_jsonb(value::text), '{}'::jsonb) AS value
  FROM public.config
  WHERE id = 'user_permissions'
), desired_roles AS (
  SELECT
    u.id,
    COALESCE(
      (SELECT pc.value -> lower(u.email) ->> 'role' FROM permission_config pc),
      u.raw_app_meta_data ->> 'role',
      'operador'
    ) AS role
  FROM auth.users u
)
UPDATE auth.users u
SET raw_app_meta_data = COALESCE(u.raw_app_meta_data, '{}'::jsonb)
                        || jsonb_build_object('role', d.role)
FROM desired_roles d
WHERE d.id = u.id
  AND d.role IN ('superadmin', 'encargado', 'duena', 'operador');

-- Falla de forma segura antes de reemplazar las policies si el proyecto aun
-- conserva roles solo en user_metadata. En ese caso se debe sembrar al menos
-- un superadmin en config.user_permissions o raw_app_meta_data y reintentar.
DO $$
DECLARE
  v_config     jsonb := '{}'::jsonb;
  v_has_config boolean := false;
  v_has_admin  boolean := false;
BEGIN
  SELECT public.te_try_jsonb(c.value::text), true
    INTO v_config, v_has_config
  FROM public.config c
  WHERE c.id = 'user_permissions'
    AND public.te_try_jsonb(c.value::text) IS NOT NULL;

  IF v_has_config THEN
    SELECT EXISTS (
      SELECT 1
      FROM auth.users u
      WHERE v_config -> lower(u.email) ->> 'role' = 'superadmin'
    ) INTO v_has_admin;
  ELSE
    SELECT EXISTS (
      SELECT 1
      FROM auth.users u
      WHERE u.raw_app_meta_data ->> 'role' = 'superadmin'
    ) INTO v_has_admin;
  END IF;

  IF NOT v_has_admin THEN
    RAISE EXCEPTION USING
      ERRCODE = 'P0001',
      MESSAGE = 'No hay un superadmin confiable en config.user_permissions ni app_metadata',
      HINT = 'Asigna role=superadmin en config.user_permissions o auth.users.raw_app_meta_data antes de ejecutar la migracion.';
  END IF;
END;
$$;

-- Reemplaza el helper RLS inseguro. Consulta auth.users y el config vigente en
-- servidor, por lo que ascensos/demisiones aplican sin esperar un JWT nuevo.
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_uid         uuid := auth.uid();
  v_email       text;
  v_app_role    text;
  v_config      jsonb := '{}'::jsonb;
  v_config_role text;
  v_has_config  boolean := false;
BEGIN
  IF v_uid IS NULL THEN
    RETURN 'anon';
  END IF;

  SELECT lower(u.email), u.raw_app_meta_data ->> 'role'
    INTO v_email, v_app_role
  FROM auth.users u
  WHERE u.id = v_uid;

  BEGIN
    SELECT value::jsonb, true INTO v_config, v_has_config
    FROM public.config
    WHERE id = 'user_permissions';
  EXCEPTION WHEN OTHERS THEN
    v_config := '{}'::jsonb;
    v_has_config := false;
  END;

  v_config_role := v_config -> v_email ->> 'role';
  IF v_config_role IN ('superadmin', 'encargado', 'duena', 'operador') THEN
    RETURN v_config_role;
  END IF;
  -- Si existe el mapa administrable, omitir/remover un usuario equivale a
  -- degradarlo a operador; no conserva para siempre el rol del rollout.
  IF v_has_config THEN
    RETURN 'operador';
  END IF;
  IF v_app_role IN ('superadmin', 'encargado', 'duena', 'operador') THEN
    RETURN v_app_role;
  END IF;
  RETURN 'operador';
END;
$$;

REVOKE ALL ON FUNCTION public.get_user_role() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_user_role() TO anon, authenticated;

-- Lee los overrides de config.id='user_permissions' y, si no existen,
-- aplica exactamente los defaults usados por shared.js.
CREATE OR REPLACE FUNCTION public.te_has_permission(p_permission text)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_email       text;
  -- app_metadata no puede modificarla el usuario. user_metadata si puede ser
  -- modificada por el propio usuario y nunca debe autorizar SECURITY DEFINER.
  v_role        text := public.get_user_role();
  v_permissions jsonb;
  v_user        jsonb;
  v_override    jsonb;
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN false;
  END IF;

  SELECT lower(u.email) INTO v_email
  FROM auth.users u
  WHERE u.id = auth.uid();

  BEGIN
    SELECT value::jsonb
      INTO v_permissions
    FROM public.config
    WHERE id = 'user_permissions';
  EXCEPTION WHEN OTHERS THEN
    v_permissions := '{}'::jsonb;
  END;

  v_user := COALESCE(v_permissions -> v_email, '{}'::jsonb);
  IF jsonb_typeof(v_user -> 'role') = 'string'
     AND (v_user ->> 'role') IN ('superadmin', 'encargado', 'duena', 'operador') THEN
    v_role := v_user ->> 'role';
  END IF;

  v_override := v_user -> p_permission;
  IF jsonb_typeof(v_override) = 'boolean' THEN
    RETURN (v_override #>> '{}')::boolean;
  END IF;

  RETURN CASE v_role
    WHEN 'superadmin' THEN p_permission IN (
      'canAddProduct', 'canEditProduct', 'canDeleteProduct', 'canPublishProduct',
      'canBulkDelete', 'canImportJSON', 'canMasivo', 'canCancelSale',
      'canEditApartado', 'canViewReports', 'canViewActivity', 'canManageSettings'
    )
    WHEN 'encargado' THEN p_permission IN (
      'canAddProduct', 'canEditProduct', 'canDeleteProduct', 'canPublishProduct',
      'canBulkDelete', 'canCancelSale'
    )
    WHEN 'duena' THEN p_permission IN (
      'canAddProduct', 'canEditProduct', 'canDeleteProduct', 'canPublishProduct',
      'canEditApartado', 'canViewReports', 'canViewActivity'
    )
    WHEN 'operador' THEN p_permission IN ('canAddProduct', 'canEditProduct')
    ELSE false
  END;
END;
$$;

