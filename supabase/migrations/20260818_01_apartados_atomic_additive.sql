-- TRES ENCANTOS
-- Fase 1: modelo auditable de pagos + RPCs atomicos para ventas y apartados.
--
-- Esta migracion es ADITIVA:
--   * conserva record_sale_atomic v1;
--   * conserva temporalmente las policies INSERT/UPDATE/DELETE actuales de sales;
--   * permite desplegar primero la base y despues el frontend sin romper clientes cacheados.
--
-- Ejecutar completa en Supabase SQL Editor. Al terminar, desplegar el frontend v2.

BEGIN;

-- Si la migracion se vuelve a ejecutar y los triggers de compatibilidad ya
-- existen, evita que el propio backfill se interprete como una operacion POS.
SELECT set_config('tresencantos.rpc_v2', 'on', true);

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- -----------------------------------------------------------------------------
-- 1. Estado explicito y marcas temporales en sales
-- -----------------------------------------------------------------------------

ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS origin_type text;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS status text;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS liquidated_at timestamptz;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS last_payment_at timestamptz;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS updated_at timestamptz;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS version bigint;

-- origin_type nunca cambia. type se mantiene por compatibilidad:
--   apartado activo -> type='apartado'
--   venta directa o apartado liquidado -> type='venta'
UPDATE public.sales
SET origin_type = CASE
  WHEN type = 'apartado' THEN 'apartado'
  WHEN jsonb_typeof(abonos) = 'array' AND jsonb_array_length(abonos) > 0 THEN 'apartado'
  ELSE 'venta'
END
WHERE origin_type IS NULL;

UPDATE public.sales
SET status = CASE
  WHEN cancelled_at IS NOT NULL THEN 'cancelado'
  WHEN origin_type = 'apartado'
       AND COALESCE(paid_amount, 0) < COALESCE(total, 0) THEN 'activo'
  ELSE 'liquidado'
END
WHERE status IS NULL;

UPDATE public.sales SET version = 0 WHERE version IS NULL;
UPDATE public.sales
SET updated_at = COALESCE(cancelled_at, created_at, now())
WHERE updated_at IS NULL;

ALTER TABLE public.sales ALTER COLUMN origin_type SET DEFAULT 'venta';
ALTER TABLE public.sales ALTER COLUMN origin_type SET NOT NULL;
ALTER TABLE public.sales ALTER COLUMN status SET DEFAULT 'liquidado';
ALTER TABLE public.sales ALTER COLUMN status SET NOT NULL;
ALTER TABLE public.sales ALTER COLUMN updated_at SET DEFAULT now();
ALTER TABLE public.sales ALTER COLUMN updated_at SET NOT NULL;
ALTER TABLE public.sales ALTER COLUMN version SET DEFAULT 0;
ALTER TABLE public.sales ALTER COLUMN version SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.sales'::regclass
      AND conname = 'sales_origin_type_check'
  ) THEN
    ALTER TABLE public.sales
      ADD CONSTRAINT sales_origin_type_check
      CHECK (origin_type IN ('venta', 'apartado')) NOT VALID;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.sales'::regclass
      AND conname = 'sales_status_check'
  ) THEN
    ALTER TABLE public.sales
      ADD CONSTRAINT sales_status_check
      CHECK (status IN ('activo', 'liquidado', 'cancelado')) NOT VALID;
  END IF;
END;
$$;

ALTER TABLE public.sales VALIDATE CONSTRAINT sales_origin_type_check;
ALTER TABLE public.sales VALIDATE CONSTRAINT sales_status_check;

CREATE INDEX IF NOT EXISTS sales_status_idx
  ON public.sales (status, created_at DESC);
CREATE INDEX IF NOT EXISTS sales_last_payment_at_idx
  ON public.sales (last_payment_at DESC)
  WHERE last_payment_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS sales_active_apartados_idx
  ON public.sales (id)
  WHERE origin_type = 'apartado' AND status = 'activo' AND cancelled_at IS NULL;

